"""Execution Router & Strict Paper Mode Guard.

Ensures that trades generated by S1/S2/S3 -> Arbiter -> RiskGovernor -> PositionManager
are routed exclusively to the Paper Trading Executor.

SmartAPI live order placement is explicitly DISABLED and blocked by architecture.
Even when SmartAPI is authenticated for data/session testing, orders cannot be placed.
"""
from __future__ import annotations

import logging
from enum import Enum
from typing import Any, Optional

import settings

log = logging.getLogger("execution.router")


class ExecutionMode(str, Enum):
    PAPER = "PAPER"
    LIVE = "LIVE"


class ExecutionSecurityError(RuntimeError):
    """Raised when an unauthorized live execution is attempted."""
    pass


class PaperExecutor:
    """Executes trades in paper simulation mode (records in journal, sends alerts)."""

    def __init__(self) -> None:
        self.is_active = True

    def execute(self, trade_intent: Any, context: Optional[dict[str, Any]] = None) -> dict[str, Any]:
        log.info(
            "PAPER_EXECUTOR: Simulated execution for intent=%s, direction=%s",
            getattr(trade_intent, "strategy_id", "UNKNOWN"),
            getattr(trade_intent, "direction", "UNKNOWN"),
        )
        return {
            "status": "PAPER_EXECUTED",
            "mode": "PAPER",
            "intent": getattr(trade_intent, "strategy_id", "UNKNOWN"),
            "order_id": f"PAPER-{getattr(trade_intent, 'strategy_id', 'TRD')}",
        }


class SmartApiExecutor:
    """SmartAPI Live Order Executor (STRICTLY DISABLED BY DEFAULT)."""

    def __init__(self) -> None:
        # Hard lock: live order execution disabled
        self.enabled = False

    def execute(self, trade_intent: Any, context: Optional[dict[str, Any]] = None) -> None:
        raise ExecutionSecurityError(
            "CRITICAL SECURITY BLOCK: SmartAPI live order execution is STRICTLY DISABLED. "
            "Under NIFTY Sniper Project Bible v2.0, Real-Money Gates in Phase 6 evaluated to FAIL. "
            "All real-capital broker routing is blocked. System must remain in PAPER mode."
        )


class ExecutionRouter:
    """Authoritative router directing TradeIntent to the designated executor.
    
    Guarantees that default execution mode is PAPER.
    """

    def __init__(self, mode: Optional[str] = None) -> None:
        configured_mode = mode or getattr(settings, "EXECUTION_MODE", "PAPER")
        self.mode = ExecutionMode.PAPER  # Hard-default to PAPER
        
        # Explicit validation
        if str(configured_mode).upper() == "LIVE":
            log.warning(
                "EXECUTION_MODE=LIVE requested, but Real-Money Gates are FAIL. "
                "Forcing ExecutionRouter to PAPER mode."
            )
            self.mode = ExecutionMode.PAPER
        else:
            self.mode = ExecutionMode.PAPER

        self.paper_executor = PaperExecutor()
        self.smartapi_executor = SmartApiExecutor()

    def route(self, trade_intent: Any, context: Optional[dict[str, Any]] = None) -> dict[str, Any]:
        """Route trade intent strictly to paper executor."""
        if self.mode == ExecutionMode.PAPER:
            return self.paper_executor.execute(trade_intent, context=context)
        else:
            # Fallback defence
            return self.smartapi_executor.execute(trade_intent, context=context)

    def is_live_enabled(self) -> bool:
        """Always returns False in current stage."""
        return False


# Global default instance
_ROUTER_INSTANCE = ExecutionRouter()


def get_execution_router() -> ExecutionRouter:
    """Get the authoritative execution router singleton."""
    return _ROUTER_INSTANCE
